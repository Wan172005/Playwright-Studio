function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-features-'));
  const options = { dataDir: path.join(root, 'data'), scriptsDir: path.join(root, 'scripts'), localScriptsDir: path.join(root, 'local'), backupDir: path.join(root, 'backups') };
  const store = new StudioStore(options);
  t.after(() => { store.close(); fs.rmSync(root, { recursive: true, force: true }); });
  return { store, root };
}
test('datasets parse .env literally, validate names/URLs, reject stale updates and stay out of summaries', t => {
  const { store, root } = fixture(t); const p = store.createProject({ name: 'A' });
  const e = store.saveEnvironment(p.id, { name: 'staging', envText: 'BASE_URL=https://staging.example.com\nUSERNAME="user #1"\nPASSWORD="keep$VALUE"\nEMPTY=\nMULTI="line1\nline2"\n' });
  assert.equal(e.variables.PASSWORD, 'keep$VALUE'); assert.equal(e.variables.EMPTY, ''); assert.equal(e.variables.MULTI, 'line1\nline2');
  assert.ok(!JSON.stringify(store.environments(p.id)).includes('keep$VALUE'));
  assert.throws(() => store.saveEnvironment(p.id, { id: e.id, name: 'staging', variables: {}, expectedUpdatedAt: 'stale' }), error => error.status === 409);
  assert.throws(() => store.saveEnvironment(p.id, { name: 'bad', variables: { BASE_URL: 'file:///tmp/a' } }), error => error.status === 400);
  assert.throws(() => store.saveEnvironment(p.id, { name: 'bad', variables: JSON.parse('{"__proto__":"bad"}') }), error => error.status === 400);
  assert.throws(() => store.environment(e.id, store.createProject({ name: 'B' }).id), error => error.status === 404);
  assert.throws(() => store.createProject({ name: 'A / staging' }), error => error.status === 409);
  assert.equal(store.backup().pending, false);
  const snapshot = path.join(root, 'backups', fs.readdirSync(path.join(root, 'backups'))[0]);
  assert.equal(JSON.parse(fs.readFileSync(path.join(snapshot, 'datasets', e.id + '.json'), 'utf8')).PASSWORD, 'keep$VALUE');
  assert.equal(fs.statSync(path.join(root, 'data/datasets', e.id + '.json')).mode & 0o777, 0o600);
});
test('copy preflights every collision, preserves exact names and rechecks confirmation hashes', t => {
  const { store } = fixture(t); const a = store.createProject({ name: 'A' }), b = store.createProject({ name: 'B' });
  const x = store.saveScript(store.target(a.id, 'Tên file.ts'), 'First', '', 'source one');
  const y = store.saveScript(store.target(a.id, 'Other.ts'), 'Second', '', 'source two');
  const existing = store.saveScript(store.target(b.id, 'Tên file.ts'), 'Existing', '', 'old');
  let conflict;
  assert.throws(() => store.copyScripts(a.id, b.id, [x.id, y.id]), error => { conflict = error.details.conflicts[0]; return error.details.code === 'COPY_OVERWRITE_REQUIRED'; });
  assert.equal(store.scripts(b.id).length, 1);
  assert.equal(fs.readFileSync(store.scriptPath(existing), 'utf8'), 'old');
  fs.writeFileSync(store.scriptPath(existing), 'external change');
  assert.throws(() => store.copyScripts(a.id, b.id, [x.id, y.id], { [x.id]: conflict.overwriteHash }), error => error.status === 409);
  const copied = store.copyScripts(a.id, b.id, [x.id, y.id], { [x.id]: hash('external change') });
  assert.equal(copied.length, 2); assert.equal(copied[0].filename, 'Tên file.ts');
  assert.equal(fs.readFileSync(store.scriptPath(existing), 'utf8'), 'source one');
  assert.equal(fs.readFileSync(store.scriptPath(x), 'utf8'), 'source one');
  assert.throws(() => store.selectedScripts(a.id, [copied[1].id]), error => error.status === 400);
  assert.throws(() => store.copyScripts(a.id, a.id, [x.id]), error => error.status === 400);
});
test('copy rolls back filesystem and SQLite after an I/O-stage failure', t => {
  const { store } = fixture(t); const a = store.createProject({ name: 'A' }), b = store.createProject({ name: 'B' });
  const scripts = ['a.ts','b.ts'].map(name => store.saveScript(store.target(a.id, name), name, '', 'new'));
  const prior = store.saveScript(store.target(b.id, 'a.ts'), 'old', '', 'keep');
  const revision = store.get('revision'); const save = store.saveScript.bind(store); let calls = 0;
  store.saveScript = (...args) => { if (++calls === 2) throw new Error('simulated failure'); return save(...args); };
  assert.throws(() => store.copyScripts(a.id, b.id, scripts.map(s => s.id), { [scripts[0].id]: hash('keep') }), /simulated failure/);
  assert.equal(store.get('revision'), revision); assert.equal(store.scripts(b.id).length, 1);
  assert.equal(fs.readFileSync(store.scriptPath(prior), 'utf8'), 'keep');
  assert.ok(!fs.existsSync(path.join(store.projectDir(b.id), 'b.ts')));
});
test('clone creates independent script and dataset IDs and can omit datasets', t => {
  const { store } = fixture(t); const a = store.createProject({ name: 'Original', url: 'https://example.com' });
  const script = store.saveScript(store.target(a.id, 'Login.ts'), 'Login', '', 'test source');
  const env = store.saveEnvironment(a.id, { name: 'staging', variables: { BASE_URL: 'https://staging.example.com', USERNAME: 'original' } });
  const cloned = store.cloneProject(a.id, { name: 'Clone' });
  assert.equal(store.scripts(cloned.id)[0].filename, script.filename); assert.notEqual(store.scripts(cloned.id)[0].id, script.id);
  const clonedEnv = store.environments(cloned.id)[0]; assert.notEqual(clonedEnv.id, env.id);
  assert.equal(store.environment(clonedEnv.id, cloned.id).variables.USERNAME, 'original');
  store.saveEnvironment(a.id, { id: env.id, name: 'staging', variables: { USERNAME: 'changed' }, expectedUpdatedAt: env.updatedAt });
  assert.equal(store.environment(clonedEnv.id, cloned.id).variables.USERNAME, 'original');
  assert.equal(store.environments(store.cloneProject(a.id, { name: 'No datasets', copyDatasets: false }).id).length, 0);
});
test('source preparation uses syntax-aware bindings and rebases only matching navigation URLs', () => {
  const filename = '/tmp/project/a.ts', runtimeFile = path.resolve(__dirname, '../runtime/dataset.ts');
  const source = `import {test} from '@playwright/test';\n// {{COMMENT}} stays a comment\ntest('test',async({page})=>{ await page.goto('https://old.example/login/{{USER}}'); await page.fill('#u','{{USER}}'); await page.goto('https://external.example/'); });`;
  const prepared = prepareSource(source, { filename, runtimeFile, baseUrl: 'https://old.example', convertUrls: true });
  assert.ok(prepared.includes('// {{COMMENT}} stays a comment'));
  assert.ok(prepared.includes('webUrl(("/login/" + data("USER")))'));
  assert.ok(prepared.includes("page.goto('https://external.example/')"));
  const again = prepareSource(prepared, { filename, runtimeFile, baseUrl: 'https://old.example', convertUrls: true });
  assert.equal(again, prepared);
  assert.throws(() => prepareSource('test(', { filename, runtimeFile }), error => error.status === 400);
  const shadowed = prepareSource(`import {test} from '@playwright/test'; test('a', async ({page}) => { const data = {}; const webUrl = ''; await page.goto('https://old.example/'); await page.fill('#u', '{{USER}}'); });`, { filename, runtimeFile, baseUrl: 'https://old.example', convertUrls: true });
  assert.ok(shadowed.includes('data as studioData')); assert.ok(shadowed.includes('webUrl as studioWebUrl'));
  assert.ok(shadowed.includes('studioData("USER")')); assert.ok(shadowed.includes('studioWebUrl("/")'));
  assert.equal(prepareSource(shadowed, { filename, runtimeFile, baseUrl: 'https://old.example', convertUrls: true }), shadowed);
});
test('HTTP batch selection, datasets, source editing, clone and copy preserve project ownership', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-api-features-'));
  const app = createStudioServer({ dataDir: path.join(root, 'data'), scriptsDir: path.join(root, 'scripts'), localScriptsDir: path.join(root, 'local'), backupDir: path.join(root, 'backups') });
  app.server.listen(0, '127.0.0.1'); await once(app.server, 'listening');
  t.after(() => { app.close(); app.store.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}`;
  async function request(url, method = 'GET', body) {
    const response = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
  }
  const a = app.store.createProject({ name: 'A', url: 'https://example.com' }), b = app.store.createProject({ name: 'B' });
  const src = `import {test} from '@playwright/test'; test('one',async({page})=>{await page.goto('https://example.com/login');});`;
  const scripts = ['one.ts','two.ts','three.ts'].map(name => app.store.saveScript(app.store.target(a.id, name), name, '', src));
  const environment = (await request(`/api/projects/${a.id}/environments`, 'POST', { name: 'staging', variables: { BASE_URL: 'https://staging.example.com', USERNAME: 'test #1', PASSWORD: 'keep$VAR', MULTILINE: 'first\nsecond', QUOTED: 'say "hello"', LITERAL: 'keep\\n' } })).body.environment;
  assert.equal(environment.variables.PASSWORD, 'keep$VAR');
  const exported = await fetch(base + `/api/projects/${a.id}/environments/${environment.id}/env`);
  assert.deepEqual({ ...parseEnv(await exported.text()) }, environment.variables);
  const summary = (await request('/api/state?projectId=' + a.id)).body;
  assert.equal(summary.environments[0].variableCount, 6); assert.ok(!JSON.stringify(summary).includes('keep$VAR'));
  let result = await request(`/api/projects/${a.id}/open-ui`, 'POST', { scriptIds: [scripts[0].id, scripts[2].id], environmentId: environment.id });
  assert.equal(result.status, 200);
  const url = new URL(result.body.url, base), filter = new RegExp(url.searchParams.get('arg'));
  assert.equal(url.searchParams.get('project'), 'A / staging');
  assert.ok(filter.test(app.store.scriptPath(scripts[0]))); assert.ok(!filter.test(app.store.scriptPath(scripts[1])));
  const selection = await request('/playwright/test/trace/studio-selection.json?id=' + url.searchParams.get('studioSelection'));
  assert.deepEqual(selection.body.files, ['one.ts','three.ts']);
  result = await request(`/api/projects/${a.id}/open-ui`, 'POST', { all: true });
  assert.equal(new URL(result.body.url, base).searchParams.has('arg'), false);
  assert.equal((await request(`/api/projects/${b.id}/open-ui`, 'POST', { scriptIds: [scripts[0].id] })).status, 400);
  const prepared = await request(`/api/scripts/${scripts[0].id}/prepare`, 'POST', { source: src, convertUrls: true });
  assert.ok(prepared.body.source.includes('webUrl'));
  const saved = await request(`/api/scripts/${scripts[0].id}/source`, 'POST', { source: prepared.body.source, expectedHash: hash(src) });
  assert.equal(saved.status, 200);
  assert.equal((await request(`/api/scripts/${scripts[0].id}/source`, 'POST', { source: src, expectedHash: hash(src) })).status, 409);
  assert.equal((await request(`/api/projects/${a.id}/copy-scripts`, 'POST', { scriptIds: [scripts[0].id,scripts[1].id], targetProjectId: b.id })).status, 200);
  const clone = await request(`/api/projects/${a.id}/clone`, 'POST', { name: 'Cloned API' });
  assert.equal(clone.status, 201); assert.equal(app.store.scripts(clone.body.project.id).length, 3);
  assert.equal(app.store.environments(clone.body.project.id).length, 1);
});
